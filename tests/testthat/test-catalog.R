test_that("routes resolve participants and moderators to exactly one session", {
  main <- catalog_fixture()
  code <- create_session(main, "Kurs B")
  cfg <- app_config(main, "secret", "https://bw.example.org")
  standard <- resolve_route(cfg, list(mocksearch = "1"))
  expect_identical(standard$kind, "session")
  expect_false(standard$mod)
  expect_identical(standard$cfg$db_path, main)
  expect_identical(standard$cfg$base_url, "https://bw.example.org")
  coded <- resolve_route(cfg, list(s = toupper(code)))
  expect_identical(coded$cfg$db_path, session_path(main, code))
  expect_identical(coded$cfg$base_url, paste0("https://bw.example.org?s=", code))
  expect_identical(coded$cfg$label, "Kurs B")
  expect_true(resolve_route(cfg, list(mod = "1", s = code))$mod)
  expect_identical(resolve_route(cfg, list(s = "zzzzzz"))$kind, "missing")
  expect_identical(resolve_route(cfg, list(s = "../../x"))$kind, "missing")
  expect_identical(resolve_route(cfg, list(mod = "1", view = "sessions"))$kind, "sessions")
  expect_identical(resolve_route(cfg, list(view = "sessions"))$kind, "session")
  unlink(session_path(main, code))
  expect_identical(resolve_route(cfg, list(s = code))$kind, "missing")
})

test_that("restarting copies reviewed settings into a new session in setup", {
  main <- catalog_fixture()
  code <- create_session(main, "Kurs C")
  expect_null(rerun_session(main, code))
  topics <- rep(list(list(t = "Thema", a = "Frage 1", b = "Frage 2")), 3)
  expect_null(configure_session(session_path(main, code), 3, 2, 120, topics))
  again <- rerun_session(main, code)
  expect_match(again, "^[2-9a-z]{6}$")
  route <- resolve_route(app_config(main, "x", "http://localhost:3838"), list(mod = "1", s = again))
  expect_identical(route$prefill, get_settings(session_path(main, code)))
  expect_identical(route$cfg$label, "Kurs C (Wiederholung)")
  expect_identical(read_table(session_path(main, again), "session")$status, "setup")
  expect_identical(rerun_session(main, again), NULL)
  expect_null(configure_session(main, 3, 3, 300, topics))
  standard_again <- rerun_session(main, NA)
  expect_identical(list_sessions(main, "http://x.org")$label[4], "Standard-Session (Wiederholung)")
  expect_match(standard_again, "^[2-9a-z]{6}$")
})

test_that("only finished sessions are archived and archiving is reversible", {
  main <- catalog_fixture()
  code <- create_session(main, "Kurs D")
  expect_match(archive_session(main, code), "beendete")
  finish_with_entry(session_path(main, code))
  expect_null(archive_session(main, code))
  cfg <- app_config(main, "secret", "http://localhost:3838")
  expect_identical(resolve_route(cfg, list(s = code))$kind, "archived")
  moderator <- resolve_route(cfg, list(mod = "1", s = code))
  expect_identical(moderator$kind, "session")
  expect_true(moderator$cfg$archived)
  expect_true(list_sessions(main, "http://x.org")$archived[2])
  expect_null(restore_session(main, code))
  expect_false(list_sessions(main, "http://x.org")$archived[2])
  expect_identical(resolve_route(cfg, list(s = code))$kind, "session")
})

test_that("archiving the standard session moves its results and frees the base address", {
  main <- catalog_fixture()
  finish_with_entry(main, "Standardidee")
  expect_null(archive_session(main, NA))
  listed <- list_sessions(main, "http://x.org")
  expect_identical(listed$status[1], "setup")
  expect_equal(nrow(read_table(main, "entries")), 0)
  expect_true(listed$archived[2])
  expect_match(listed$label[2], "^Standard-Session vom ")
  copy <- session_path(main, listed$code[2])
  expect_identical(read_table(copy, "entries")$text, "Standardidee")
  expect_identical(read_table(copy, "session")$status, "finished")
  con <- db(copy)
  on.exit(DBI::dbDisconnect(con))
  expect_false(DBI::dbExistsTable(con, "catalog"))
  expect_match(archive_session(main, NA), "beendete")
})

test_that("deleting removes a session completely while the standard session is reset", {
