test_that("connections never recreate a missing session database", {
  path <- file.path(withr::local_tempdir(), "gone.sqlite")
  expect_error(db(path))
  expect_false(file.exists(path))
  init_db(path)
  pid <- add_participant(path, "Vor dem Loeschen")
  unlink(path)
  expect_error(save_entry(path, pid, 1, 1, 1, 1, "Verspaeteter Entwurf"))
  expect_false(file.exists(path))
})

test_that("a forced reset clears a session in any state", {
  path <- new_db(withr::local_tempfile(), n = 3)
  start_session(path)
  expect_false(reset_session(path))
  expect_true(reset_session(path, force = TRUE))
  expect_identical(read_table(path, "session")$status, "setup")
  expect_equal(nrow(read_table(path, "participants")), 0)
})

test_that("new sessions get their own database file, code and address", {
  main <- catalog_fixture()
  a <- create_session(main, "Kurs A")
  b <- create_session(main)
  expect_match(c(a, b), "^[2-9abcdefghjkmnpqrstuvwxyz]{6}$")
  expect_false(identical(a, b))
  expect_true(file.exists(file.path(dirname(main), "sessions", paste0(a, ".sqlite"))))
  expect_identical(read_table(session_path(main, a), "session")$status, "setup")
  listed <- list_sessions(main, "https://bw.example.org")
  expect_identical(listed$code, c(NA, a, b))
  expect_identical(listed$label[1:2], c("Standard-Session", "Kurs A"))
  expect_match(listed$label[3], "^Session ")
  expect_identical(listed$url, c("https://bw.example.org",
                                 paste0("https://bw.example.org?s=", c(a, b))))
  expect_identical(session_url("https://x.org/?lang=de", a), paste0("https://x.org/?lang=de&s=", a))
  expect_identical(listed$status, rep("setup", 3))
  expect_false(any(listed$archived))
})

